const dict: Record<Lang, Record<TKey, string>> = { en, ta }

type Ctx = {
  lang: Lang
  setLang: (l: Lang) => void
  t: (k: TKey) => string
  tradeName: (trade: string) => string
}

const LangContext = createContext<Ctx>({
  lang: 'en',
  setLang: () => {},
  t: (k) => en[k],
  tradeName: (tr) => tr,
})

function readLang(): Lang {
  try {
    const v = localStorage.getItem('lang')
    if (v === 'en' || v === 'ta') return v
  } catch {
    /* storage unavailable */
  }
  return 'ta'
}

export function LangProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(readLang)

  const value = useMemo<Ctx>(() => {
    const t = (k: TKey) => dict[lang][k] ?? en[k] ?? k
    return {
      lang,
      setLang: (l) => {
        setLangState(l)
        document.documentElement.lang = l
        try {
          localStorage.setItem('lang', l)
        } catch {
          /* ignore */
        }
      },
      t,
      tradeName: (trade) => t(((TRADES as readonly string[]).includes(trade) ? `trades_${trade}` : 'trades_other') as TKey),
    }
  }, [lang])

  return <LangContext.Provider value={value}>{children}</LangContext.Provider>
}

export const useT = () => useContext(LangContext)

export const localName = (o: { name_en: string; name_ta: string }, lang: Lang) => (lang === 'ta' ? o.name_ta : o.name_en)
